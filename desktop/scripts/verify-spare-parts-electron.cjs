const js = async code => { try { return await window.webContents.executeJavaScript(`(async () => { return ${code} })()`) } catch (error) { throw new Error(error.message + '\nExpression: ' + code) } }
async function waitFor(code) {
  const until = Date.now() + 20000
  while (Date.now() < until) {
    if (await js(`Promise.resolve(${code}).then(Boolean)`)) return
    await new Promise(resolve => setTimeout(resolve, 100))
  }
  throw new Error('Timed out: ' + code + '\n' + await js('document.body.innerText.slice(-4000)'))
}
async function check(name, code) { assert.equal(await js(code), true, name); checks.push(name) }
async function screenshot(name) {
  await js('document.fonts.ready.then(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))')
  await writeFile(join(output, name + '.png'), (await window.webContents.capturePage()).toPNG())
}
async function fill(label, value) {
  await waitFor(`[...document.querySelectorAll('label.field')].some(l => l.querySelector('span')?.textContent.startsWith(${JSON.stringify(label)}))`)
  await js(`(() => { const field = [...document.querySelectorAll('label.field')].find(l => l.querySelector('span')?.textContent.startsWith(${JSON.stringify(label)})); if (!field) throw new Error('Missing field: '+${JSON.stringify(label)}); const input = field.querySelector('input'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(input, ${JSON.stringify(String(value))}); input.dispatchEvent(new Event('input', {bubbles:true})); input.dispatchEvent(new Event('change', {bubbles:true})); })()`)
}
async function click(text, scope = 'document') {
  await js(`(() => { const button = [...${scope}.querySelectorAll('button')].find(b => b.textContent.trim().startsWith(${JSON.stringify(text)})); if (!button) throw new Error('Missing button: '+${JSON.stringify(text)}); button.click() })()`)
}
